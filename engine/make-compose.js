// Generates docker-compose.yml for the Phala CVM.
//
// No custom image: the engine is bundled into one file (npm run bundle ->
// dist/engine.mjs, every dependency inlined) and committed. The compose runs
// the official node:22-alpine image (pinned by digest), downloads that file
// from this repo at a fixed commit, and refuses to start unless its sha256
// matches the hash written below. Phala's RTMR3 covers the whole compose file,
// hash included, so the attestation quote pins the exact engine code. Anyone
// can rebuild the bundle from the same commit and compare.
//
//   npm run bundle && git commit && git push
//   node make-compose.js [commit]        (default: HEAD)
//   npx phala deploy -n attest-arc-engine -c docker-compose.yml -e ADMIN_KEY=...
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const REPO = "ynsmlkc/attest-arc";
const NODE_IMAGE = "node:22-alpine@sha256:0a7108bf6c7bf5de370ffb1a3ed6be93d405b43ff159f681a8d18c0e2bc2e402";

const git = (...args) => execFileSync("git", args, { cwd: here, encoding: "utf8" }).trim();
const commit = git("rev-parse", process.argv[2] || "HEAD");
// Hash the committed bytes, not the working tree: that is what gets downloaded.
const committed = execFileSync("git", ["show", `${commit}:engine/dist/engine.mjs`], { cwd: here });
const sha = crypto.createHash("sha256").update(committed).digest("hex");
const local = crypto.createHash("sha256").update(fs.readFileSync(path.join(here, "dist", "engine.mjs"))).digest("hex");
if (local !== sha) console.warn(`warning: working-tree dist/engine.mjs (${local}) differs from ${commit}`);

const url = `https://raw.githubusercontent.com/${REPO}/${commit}/engine/dist/engine.mjs`;
const compose = `# GENERATED by make-compose.js -- see that file. Deployed to Phala Cloud as a
# TDX CVM. RTMR3 covers this file, so the sha256 below pins the engine code.
# Source: ${REPO}@${commit} engine/dist/engine.mjs
services:
  engine:
    image: ${NODE_IMAGE}
    entrypoint:
      - sh
      - -c
      - >-
        mkdir -p /app && cd /app &&
        wget -q -O engine.mjs ${url} &&
        echo "${sha}  engine.mjs" | sha256sum -c - &&
        exec node engine.mjs
    volumes:
      - /var/run/dstack.sock:/var/run/dstack.sock
    ports:
      - "80:80"
    environment:
      # Vault/verifier/enclave id are set after boot via POST /configure, so
      # repointing the engine never changes RTMR3.
      - ARC_RPC_URL=https://rpc.mainnet.arc.io
      - ARC_CHAIN_ID=5042
      - ENGINE_KEY_PATH=attest-arc/matching-engine/v1
      # Sealed env var (encrypted to the CVM), never written here in plaintext.
      - ADMIN_KEY=\${ADMIN_KEY}
    restart: always
`;

fs.writeFileSync(path.join(here, "docker-compose.yml"), compose);
console.log(`docker-compose.yml written for ${commit}, engine sha256 ${sha}`);
